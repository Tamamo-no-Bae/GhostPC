// helpers shared between the D3D source files
inline DWORD XType(const XResource *r) { return r->Common & XCOMMON_TYPE_MASK; }
inline DWORD XFormat(const XPixelContainer *p) { return (p->Format & XFMT_FORMAT_MASK) >> XFMT_FORMAT_SHIFT; }
