# make_lod_caps.py -- writes src/lodcaps.h: the models whose reduced levels of detail (the Xbox's, LOD 1-3) drop parts
# of a skinned mesh, with the highest level each may use (user: far off the Hydralisk lost everything from the waist
# down: in hydralisk.nod group 10's LOD 3 no triangle uses bones 1, 16-19, its lower body and tail).
# A model is listed when, in a group with per-vertex bones (vertex set type 1), some LOD uses fewer bones than LOD 0;
# its cap is the level before the first such LOD. (Static models whose LOD 1-3 are empty are left alone: the engine
# draws those whole.) vehicles.cpp holds a model instance at its cap (cModelInst::SetDetail).
import glob
import os
import struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
MODELS = os.path.join(ROOT, "game", "3D", "Models")
OUT = os.path.join(ROOT, "src", "lodcaps.h")
VSIZE = {0: 32, 1: 36, 2: 48}


def first_bad_lod(path):
    d = open(path, "rb").read()
    if len(d) < 0x5c or struct.unpack_from("<I", d, 0)[0] != 10:
        return None
    nmat, nbones, nsets, ngroups = d[4], d[5], d[6], d[7]
    nidx = struct.unpack_from("<I", d, 0x44)[0]
    sets = [struct.unpack_from("<II", d, 0x24 + 8 * i) for i in range(nsets)]
    o = 92 + 32 * nmat + 64 * nbones
    vstart = []
    for typ, cnt in sets:
        vstart.append(o)
        o += VSIZE.get(typ, 32) * cnt
    p, o = o, o + 2 * nidx
    if o + 56 * ngroups > len(d):
        return None
    vbase, bad = [0] * nsets, None
    for g in range(ngroups):
        r = d[o + 56 * g:o + 56 * g + 56]
        v = struct.unpack_from("<13H", r, 4)
        lods, vc, s = [v[3 * l:3 * l + 3] for l in range(4)], v[12], r[0x36]
        typ = sets[s][0]
        used = []
        for strip, lst, _ in lods:
            ids = struct.unpack_from("<%dH" % (strip + lst), d, p)
            p += 2 * (strip + lst)
            if typ == 1:
                used.append({struct.unpack_from("<I", d, vstart[s] + 36 * (vbase[s] + i) + 32)[0] for i in set(ids) if i < vc})
        vbase[s] += vc
        if typ == 1:
            for l in range(1, 4):
                if used[0] - used[l]:
                    bad = l if bad is None else min(bad, l)
                    break
    return bad


def main():
    caps = []
    for f in sorted(glob.glob(os.path.join(MODELS, "*.nod"))):
        try:
            bad = first_bad_lod(f)
        except (struct.error, IndexError):
            continue
        if bad is not None:
            caps.append((os.path.basename(f), bad - 1))
    with open(OUT, "w", newline="\n") as h:
        h.write("// generated by scripts/make_lod_caps.py: models whose reduced levels of detail drop parts of a skinned mesh,\n")
        h.write("// and the highest level each may use (vehicles.cpp)\n#pragma once\n")
        h.write("static const struct { const char *model; int maxLod; } LOD_CAPS[] = {\n")
        for name, cap in caps:
            h.write('    {"%s", %d},\n' % (name, cap))
        h.write("};\n")
    print("wrote %s: %d models" % (OUT, len(caps)))


if __name__ == "__main__":
    main()
