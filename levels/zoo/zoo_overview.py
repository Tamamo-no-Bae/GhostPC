"""Overview of the Enemy Zoo, written by make_zoo_map.py each time it runs: ZOO_OVERVIEW.md (rooms, doors, placed
templates and level-script boxes in world coordinates, the ones the game, its logs and the GHOSTPC_* debug variables
use) and zoo_overview.svg / .png (a top-down plan of the same). Map (script) coordinates + OFFSET = world coordinates."""
import os
import re

BOSSES = {"Vulcan", "Hauler_Boss", "Goliath_232", "Goliath_222c", "sniper_boss", "lurker_boss", "ultralisk",
          "Tanagazj", "BossTanagazj"}


def write(g):
    here, off = g["HERE"], g["OFFSET"]
    W = lambda x, y: (x + off[0], y + off[1])   # map -> world

    # named areas: every module-level (x0, y0, x1, y1) rectangle, the Ultralisk loop pieces too
    areas = []
    for k, v in g.items():
        if k.isupper() and k != "BOUNDS" and isinstance(v, tuple) and len(v) == 4 and \
                all(isinstance(c, (int, float)) for c in v) and v[0] < v[2] and v[1] < v[3]:
            areas.append((k, v))
    for side, parts in g.get("U_LOOPS", {}).items():
        for n, r in zip(("left leg", "cross leg", "right leg", "block"), parts):
            areas.append(("U_LOOP %s %s" % (side, n), r))

    def area_at(x, y):
        hits = [(r[2] - r[0]) * (r[3] - r[1]) for _, r in areas if r[0] <= x <= r[2] and r[1] <= y <= r[3]]
        best = [(a, n) for (n, r), a in zip([(n, r) for n, r in areas if r[0] <= x <= r[2] and r[1] <= y <= r[3]], hits)]
        return min(best)[1] if best else "outside"

    # doors: centre of each gap, named by the areas on its two sides
    doors = []
    for x0, y0, x1, y1, along_x, ds, height in g["WALL_LOG"]:
        for c in ds:
            if along_x:
                cx, cy = c, (y0 + y1) / 2
                a, b = area_at(cx, y0 - 0.6), area_at(cx, y1 + 0.6)
            else:
                cx, cy = (x0 + x1) / 2, c
                a, b = area_at(x0 - 0.6, cy), area_at(x1 + 0.6, cy)
            doors.append((cx, cy, "x" if along_x else "y", a, b))

    # level-script boxes and start (already in world coordinates)
    notify, start = [], None
    gpc = os.path.join(here, "out_levelscript.gpc")
    if os.path.exists(gpc):
        for line in open(gpc, encoding="latin1"):
            m = re.match(r"\s*notify\s+(\S+) (\S+) (\S+) (\S+) (\S+) (\S+) (\S+) (\S+)", line)
            if m:
                notify.append(tuple(float(v) for v in m.groups()[:6]) + m.groups()[6:])
            m = re.match(r"\s*player_start\s+(\S+) (\S+) (\S+)", line)
            if m:
                start = tuple(float(v) for v in m.groups())

    placed = [(n, o, yaw) for n, o, yaw in g["PLACED"]]

    def f(v):
        return ("%.1f" % v).rstrip("0").rstrip(".")

    # ---- markdown
    L = ["# Enemy Zoo overview", "",
         "Generated by make_zoo_map.py (zoo_overview.py); do not edit. **All coordinates are world coordinates** "
         "(metres; what the game, ghostpc.log and the GHOSTPC_* debug variables use). Map = world - OFFSET; "
         "OFFSET = (%s, %s, %s). Floors are at z %s; yaw 0 = +Y (north), 90 = -X (west)." % (
             f(off[0]), f(off[1]), f(off[2]), f(off[2])), "",
         "Player: created at the world origin (the sniper arena), moved to the spawn room by the level script"
         + (" to %s %s %s." % tuple(f(v) for v in start) if start else "."), "",
         "## Areas", "", "| area | x from | x to | y from | y to | centre |", "|---|---|---|---|---|---|"]
    for n, r in sorted(areas, key=lambda a: a[0]):
        (ax, ay), (bx, by) = W(r[0], r[1]), W(r[2], r[3])
        L.append("| %s | %s | %s | %s | %s | %s %s |" % (n, f(ax), f(bx), f(ay), f(by), f((ax + bx) / 2), f((ay + by) / 2)))
    L += ["", "## Doors (%g m wide, %g m high)" % (g["DOOR_W"], g["DOOR_H"]), "",
          "| # | between | centre x | centre y | wall runs along |", "|---|---|---|---|---|"]
    for i, (cx, cy, ax, a, b) in enumerate(sorted(doors, key=lambda d: (d[3], d[4])), 1):
        wx, wy = W(cx, cy)
        L.append("| %d | %s / %s | %s | %s | %s |" % (i, a, b, f(wx), f(wy), ax))
    if notify:
        L += ["", "## Boss triggers (level script notify boxes)", "",
              "| AI class | message | x | y | z |", "|---|---|---|---|---|"]
        for n in notify:
            L.append("| %s | %s | %s .. %s | %s .. %s | %s .. %s |" % (n[6], n[7], f(n[0]), f(n[3]), f(n[1]), f(n[4]),
                                                                      f(n[2]), f(n[5])))
    L += ["", "## Placed templates", "", "z is where the placement starts it (models raised by RAISE start higher).", "",
          "| template | area | x | y | z | yaw |", "|---|---|---|---|---|---|"]
    for n, o, yaw in sorted(placed, key=lambda p: (area_at(p[1][0], p[1][1]), p[0])):
        wx, wy = W(o[0], o[1])
        L.append("| %s%s | %s | %s | %s | %s | %s |" % (n, " (boss)" if n in BOSSES else "", area_at(o[0], o[1]),
                                                       f(wx), f(wy), f(o[2] + off[2]), f(yaw)))
    open(os.path.join(here, "ZOO_OVERVIEW.md"), "w", newline="\n").write("\n".join(L) + "\n")

    # ---- plan (world coordinates, north up): shapes drawn as zoo_overview.svg and zoo_overview.png
    b = g["BOUNDS"]
    (x0, y0), (x1, y1) = W(b[0] - 4, b[1] - 4), W(b[2] + 4, b[3] + 4)
    s = 4.0
    width, height = int((x1 - x0) * s), int((y1 - y0) * s)
    X = lambda x: (x - x0) * s
    Y = lambda y: (y1 - y) * s
    P = []   # ("line", x0, y0, x1, y1, colour, w) / ("rect", x, y, w, h, fill, outline, dashed) / ("circle", x, y, r,
    #          fill, outline) / ("text", x, y, text, colour, size, bold)
    for gx in range(int(x0 // 10 * 10), int(x1) + 1, 10):   # 10 m grid, labelled every 50 m
        P.append(("line", X(gx), 0, X(gx), height, "#e2e0d8", 1.2 if gx % 50 == 0 else 0.5))
        if gx % 50 == 0:
            P.append(("text", X(gx) + 2, 9, "x %d" % gx, "#888888", 7, False))
    for gy in range(int(y0 // 10 * 10), int(y1) + 1, 10):
        P.append(("line", 0, Y(gy), width, Y(gy), "#e2e0d8", 1.2 if gy % 50 == 0 else 0.5))
        if gy % 50 == 0:
            P.append(("text", 2, Y(gy) - 2, "y %d" % gy, "#888888", 7, False))
    for n, r in areas:   # area labels
        if n.startswith("U_LOOP") or (r[2] - r[0]) * (r[3] - r[1]) < 150:
            continue
        (ax, ay), (bx, by) = W(r[0], r[1]), W(r[2], r[3])
        P.append(("text", X(ax) + 4, Y(by) + 14, n, "#9a958a", 11, True))
    for wx0, wy0, wx1, wy1, along_x, ds, h in g["WALL_LOG"]:   # walls (door gaps drawn over them)
        (ax, ay), (bx, by) = W(wx0, wy0), W(wx1, wy1)
        P.append(("rect", X(ax), Y(by), (bx - ax) * s, (by - ay) * s, "#55524b" if h > 10 else "#8d897f", None, False))
    for i, (cx, cy, ax, a, b2) in enumerate(sorted(doors, key=lambda d: (d[3], d[4])), 1):
        wx, wy = W(cx, cy)
        dw = g["DOOR_W"] * s
        if ax == "x":
            P.append(("rect", X(wx) - dw / 2, Y(wy) - 3, dw, 6, "#e07b1f", None, False))
        else:
            P.append(("rect", X(wx) - 3, Y(wy) - dw / 2, 6, dw, "#e07b1f", None, False))
        P.append(("text", X(wx) + 5, Y(wy) - 4, "D%d (%s, %s)" % (i, f(wx), f(wy)), "#b35a0b", 7, True))
    for n in notify:   # trigger boxes
        P.append(("rect", X(n[0]), Y(n[4]), (n[3] - n[0]) * s, (n[4] - n[1]) * s, None, "#c0392b", True))
    for n, o, yaw in placed:   # templates
        wx, wy = W(o[0], o[1])
        boss = n in BOSSES
        pick = n.startswith("pow")
        col = "#c0392b" if boss else "#2a7f62" if pick else "#2c5aa0"
        P.append(("circle", X(wx), Y(wy), 4 if boss else 1.6, col, None))
        if not pick:
            P.append(("text", X(wx) + 3, Y(wy) + 2.5, n, col, 9 if boss else 7, boss))
    if start:
        P.append(("circle", X(start[0]), Y(start[1]), 4, None, "#111111"))
        P.append(("text", X(start[0]) + 6, Y(start[1]) + 3, "start", "#111111", 7, True))
    P.append(("circle", X(0), Y(0), 3, "#111111", None))
    P.append(("text", X(0) + 5, Y(0) + 3, "world origin", "#111111", 7, False))

    esc = lambda t: t.replace("&", "&amp;").replace("<", "&lt;")
    out = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" font-family="Segoe UI, Arial">' % (width, height),
           '<rect width="100%" height="100%" fill="#f7f6f2"/>']
    for p in P:
        if p[0] == "line":
            out.append('<line x1="%g" y1="%g" x2="%g" y2="%g" stroke="%s" stroke-width="%g"/>' % p[1:])
        elif p[0] == "rect":
            out.append('<rect x="%g" y="%g" width="%g" height="%g" fill="%s"%s%s/>' % (
                p[1], p[2], p[3], p[4], p[5] or "none", ' stroke="%s"' % p[6] if p[6] else "",
                ' stroke-dasharray="4 3"' if p[7] else ""))
        elif p[0] == "circle":
            out.append('<circle cx="%g" cy="%g" r="%g" fill="%s"%s/>' % (
                p[1], p[2], p[3], p[4] or "none", ' stroke="%s" stroke-width="1.5"' % p[5] if p[5] else ""))
        else:
            out.append('<text x="%g" y="%g" fill="%s" font-size="%g"%s>%s</text>' % (
                p[1], p[2], p[4], p[5], ' font-weight="700"' if p[6] else "", esc(p[3])))
    out.append("</svg>")
    open(os.path.join(here, "zoo_overview.svg"), "w", newline=chr(10)).write(chr(10).join(out) + chr(10))
    try:   # the same as a PNG (Pillow), drawn at 2x
        from PIL import Image, ImageDraw, ImageFont
        k = 2
        im = Image.new("RGB", (width * k, height * k), "#f7f6f2")
        d = ImageDraw.Draw(im)
        fonts = {}

        def font(size, bold):
            key = (size, bold)
            if key not in fonts:
                for name in (("arialbd.ttf" if bold else "arial.ttf"), "DejaVuSans.ttf"):
                    try:
                        fonts[key] = ImageFont.truetype(name, int(size * k))
                        break
                    except OSError:
                        pass
                else:
                    fonts[key] = ImageFont.load_default()
            return fonts[key]
        for p in P:
            if p[0] == "line":
                d.line([p[1] * k, p[2] * k, p[3] * k, p[4] * k], fill=p[5], width=max(1, int(p[6] * k)))
            elif p[0] == "rect":
                box = [p[1] * k, p[2] * k, (p[1] + p[3]) * k, (p[2] + p[4]) * k]
                d.rectangle(box, fill=p[5], outline=p[6], width=2 if p[6] else 0)
            elif p[0] == "circle":
                r = p[3] * k
                d.ellipse([p[1] * k - r, p[2] * k - r, p[1] * k + r, p[2] * k + r], fill=p[4], outline=p[5],
                          width=3 if p[5] else 0)
            else:
                fnt = font(p[5], p[6])
                d.text((p[1] * k, p[2] * k), p[3], fill=p[4], font=fnt, anchor="ls")
        im.save(os.path.join(here, "zoo_overview.png"))
    except ImportError:
        pass
    print("overview: %d areas, %d doors, %d placements -> ZOO_OVERVIEW.md, zoo_overview.svg/.png" % (len(areas), len(doors),
                                                                                              len(placed)))
